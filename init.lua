vim.keymap.set("n", "<leader>g", function()
	local search = vim.fn.input("Search for: ")

	if search ~= "" then
		vim.cmd("silent grep! " .. search)
		vim.cmd("copen")
		vim.cmd("redraw!")
	end
end)
